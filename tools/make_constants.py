"""Developer tool: write u2c_customfw/firmware/stock_hashes.py from a local copy of 8BitDo's v1.09 .dat.

    make_constants.py ultimate-2c-controller-v1.09.dat

Only SHA-256 hashes are written: of each edit region of the stock app area, and of that area with all regions zeroed.
"""
import argparse
import hashlib
import sys
from pathlib import Path

from u2c_customfw.firmware import image, recipes

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('dat',nargs='?',type=Path)
parser.add_argument('--backup',type=Path,help='Full controller backup containing a verified original 1.09 bank')
args=parser.parse_args()
if args.backup:
    data=args.backup.read_bytes()
    if len(data)!=image.FLASH_SIZE:parser.error('Expected a full controller backup')
    stock=next((data[a:a+image.BANK_A_SIZE] for a in (image.BASE,image.BANK_B) if hashlib.sha256(data[a:a+image.BANK_A_SIZE]).hexdigest()==image.STOCK_SHA256),None)
    if stock is None:parser.error('No verified original firmware 1.09 bank')
elif args.dat:
    dat=args.dat.read_bytes()
    if hashlib.sha256(dat).hexdigest()!=image.STOCK_DAT_SHA256:parser.error("Not 8BitDo's controller v1.09 .dat")
    stock=dat[0x1c:]
else:parser.error('Provide a .dat or --backup')
assert hashlib.sha256(stock).hexdigest()==image.STOCK_SHA256
stock = recipes.whole(stock)
sha = lambda b: hashlib.sha256(b).hexdigest()
regions = {(e.addr, e.size): sha(recipes._region(stock, e)) for r in recipes.RECIPES.values() for e in r.edits}
out = Path(recipes.__file__).with_name("stock_hashes.py")
lines = ["# SPDX-License-Identifier: GPL-3.0-or-later", "# Generated by tools/make_constants.py: hashes only, no 8BitDo bytes.",
         "REGION_SHA256 = {"] + [f"    ({a:#x}, {n}): \"{h}\"," for (a, n), h in sorted(regions.items())] + [
         "}", f"REMAINDER_SHA256 = \"{sha(recipes.masked(stock))}\"", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out} ({len(regions)} regions)")
