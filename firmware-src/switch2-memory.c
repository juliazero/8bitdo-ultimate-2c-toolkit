static u32 address32(const u8 *r) {return r[0]|((u32)r[1]<<8)|((u32)r[2]<<16)|((u32)r[3]<<24);}
u32 y_memory_request(struct y_pairing *ctx,const u8 *r,u32 length,u8 *out) {
    u32 address,size,i,offset,digit;u8 value;
    if(length!=16 || r[3]!=4 || r[5]!=8 || r[9]!=0x7e || r[10] || r[11]) return 0;
    size=r[8];address=address32(r+12);
    if(!size || size>64) return 0;
    if(!((address>=0x13000 && address<=0x13160-size) ||
         (address>=0x1fc000 && address<=0x1fc080-size))) return 0;
    out[8]=size;out[9]=0;out[10]=0;out[11]=0;
    for(i=0;i<4;i++) out[12+i]=r[12+i];
    for(i=0;i<size;i++) {
        value=255;
        if(address<0x1fc000) {
            offset=address+i-0x13000;value=factory[offset];
            if(offset==2) value='U';
            else if(offset==3) value='2';
            else if(offset>=4 && offset<16) {
                digit=ctx->address[(offset-4)>>1];
                digit=(offset&1)?(digit&15):(digit>>4);
                value=digit<10?'0'+digit:'A'+digit-10;
            } else if(offset==16 || offset==17) value=0;
        }
        out[16+i]=value;
    }
    out[0]=2;out[1]=1;out[2]=1;out[3]=4;out[4]=0x10;out[5]=0x78;out[6]=0;out[7]=0;
    return size+16;
}
